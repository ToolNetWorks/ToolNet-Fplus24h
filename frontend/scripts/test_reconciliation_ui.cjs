assert.doesNotMatch(api, /method: "POST"|method: "PATCH"|method: "DELETE"/);
assert.match(screen, /Đối soát & Cảnh báo/);
assert.match(screen, /không được tự động thử lại/);
assert.doesNotMatch(screen, /fetch\(.*method:\s*"POST"/);
