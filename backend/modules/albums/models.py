import uuid
from django.core.exceptions import ValidationError
from django.db import models
from modules.pipelines.models import Pipeline
class Album(models.Model):
    id = models.UUIDField(
        primary_key=True,
        default=uuid.uuid4,
        editable=False,
    )
    pipeline = models.ForeignKey(
        Pipeline,
        on_delete=models.PROTECT,
        related_name="albums",
    )
    name = models.CharField(
        max_length=200,
    )
    description = models.TextField(
        blank=True,
        default="",
    )
    is_enabled = models.BooleanField(
        default=True,
        db_index=True,
    )
    created_at = models.DateTimeField(
        auto_now_add=True,
    )
    updated_at = models.DateTimeField(
        auto_now=True,
    )
    class Meta:
        db_table = "publisher_albums"
        ordering = [
            "-created_at",
            "-id",
        ]
        indexes = [
            models.Index(
                fields=["pipeline", "is_enabled"],
                name="album_pipeline_enabled_idx",
            ),
        ]
    def clean(self):
        super().clean()
        self.name = (self.name or "").strip()
        if not self.name:
            raise ValidationError({
                "name": "Tên Album không được để trống."
            })
    def __str__(self):
        return self.name
class AlbumImage(models.Model):
    class UploadStatus(models.TextChoices):
        PENDING = "pending", "Chờ upload"
        READY = "ready", "Sẵn sàng"
        FAILED = "failed", "Upload thất bại"
    id = models.UUIDField(
        primary_key=True,
        default=uuid.uuid4,
        editable=False,
    )
    album = models.ForeignKey(
        Album,
        on_delete=models.PROTECT,
        related_name="images",
    )
    original_filename = models.CharField(
        max_length=255,
    )
    # Object key generated by the backend.
    # Never trust a user-supplied object key.
    storage_key = models.CharField(
        max_length=500,
        unique=True,
        null=True,
        blank=True,
        editable=False,
    )
    mime_type = models.CharField(
        max_length=50,
        blank=True,
    )
    file_size = models.PositiveBigIntegerField(
        default=0,
    )
    width = models.PositiveIntegerField(
        null=True,
        blank=True,
    )
    height = models.PositiveIntegerField(
        null=True,
        blank=True,
    )
    sha256 = models.CharField(
        max_length=64,
        blank=True,
        editable=False,
    )
    position = models.PositiveIntegerField(
        default=0,
    )
    upload_status = models.CharField(
        max_length=20,
        choices=UploadStatus.choices,
        default=UploadStatus.PENDING,
        db_index=True,
    )
    created_at = models.DateTimeField(
        auto_now_add=True,
    )
    updated_at = models.DateTimeField(
        auto_now=True,
    )
    class Meta:
        db_table = "publisher_album_images"
        ordering = [
            "position",
            "created_at",
            "id",
        ]
        indexes = [
            models.Index(
                fields=["album", "position"],
                name="album_image_position_idx",
            ),
            models.Index(
                fields=["album", "upload_status"],
                name="album_image_status_idx",
            ),
        ]
    def clean(self):
        super().clean()
        self.original_filename = (
            self.original_filename or ""
        ).strip()
        if not self.original_filename:
            raise ValidationError({
                "original_filename": "Thiếu tên file ảnh."
            })
        if self.upload_status != self.UploadStatus.READY:
            return
        if (
            not self.storage_key
            or self.file_size <= 0
            or not self.width
            or not self.height
            or self.mime_type not in {
                "image/jpeg",
                "image/png",
                "image/webp",
            }
            or len(self.sha256) != 64
            or any(
                char not in "0123456789abcdef"
                for char in self.sha256.lower()
            )
        ):
            raise ValidationError(
                "Metadata ảnh đã upload không hợp lệ."
            )
    def __str__(self):
        return self.original_filename
